-- ============================================================
-- 364_kb_audit_history_cleanup.sql
-- Разовая очистка журнала: удалить накопленные события базы знаний.
--
-- Решение владельца 20.11.2026: всё, что журнал успел записать про базу
-- знаний (kb_page.*, kb_thread.*: создание, правки, переименования,
-- перемещения, удаления, обсуждения), удаляется. Новые события базы
-- знаний пишутся дальше как прежде — триггеры и функции не меняются.
--
-- Отсечка по времени, а не «всё на момент применения»: миграцию
-- накатывают на прод вручную после мержа, и события, записанные после
-- решения, удалять нельзя.
--
-- Что пропадает вместе с записями:
--   • лента «Журнал событий», раздел «База знаний», до отсечки;
--   • структурные события в ленте обновлений страницы (kb_list_page_updates,
--     audit-ветка) — правки по версиям остаются (kb_page_versions);
--   • счётчик и «Последние изменения» на дашборде базы знаний.
-- Восстановление удалённых страниц доступно в корзине базы знаний.
-- Необратимо: строки удаляются, копии нет.
-- ============================================================

do $$
declare
  v_deleted integer;
begin
  delete from public.audit_logs
   where created_at < timestamptz '2026-11-20 21:00:00+03'
     and (
       entity_type in ('kb_page', 'kb_thread')
       or action_code like 'kb\_page.%'
       or action_code like 'kb\_thread.%'
     );
  get diagnostics v_deleted = row_count;
  raise notice 'Удалено записей базы знаний из журнала: %', v_deleted;
end;
$$;
