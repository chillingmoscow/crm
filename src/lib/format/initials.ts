/**
 * Инициалы для аватара человека без фото: первые буквы первых двух слов
 * имени («Тест Владелец» → «ТВ»), для имени из одного слова — одна буква,
 * для пустого — «?». Слова, начинающиеся не с буквы или цифры, пропускаются.
 * Один источник для всех аватаров людей (DS «Аватары и цвет»): таблицы,
 * карточки, журналы, комментарии, упоминания.
 */
export function personInitials(name?: string | null): string {
  const letters = (name ?? "")
    .trim()
    .split(/\s+/)
    // Разделители вроде «·» или «—» («Анна · тест») словами не считаем.
    .filter((word) => /^[\p{L}\p{N}]/u.test(word))
    .slice(0, 2)
    .map((word) => Array.from(word)[0] ?? "")
    .join("")
    .toLocaleUpperCase("ru");
  return letters || "?";
}
