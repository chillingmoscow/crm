export function InboxHelp() {
  return (
    <>
      <section className="space-y-2">
        <h3 className="font-semibold">Что здесь</h3>
        <p>
          Повторяющиеся платежи, у которых наступил срок. Каждый срок — своя
          карточка: два пропущенных месяца связи дадут две карточки. Пока платёж
          не проведён, он не меняет остатки счетов и не попадает в отчёты.
        </p>
      </section>
      <section className="space-y-2">
        <h3 className="font-semibold">Как разобрать</h3>
        <p>
          Карточки идут по одной, старые первыми; стрелки в шапке листают
          очередь. Проверьте сумму, статью, заведение и дату и выберите:
        </p>
        <ul className="list-disc space-y-1 pl-5">
          <li>«Провести» — появится операция в «Транзакциях»;</li>
          <li>«Пропустить этот раз» — операции не будет, следующий срок придёт как обычно;</li>
          <li>«Перенести» — карточка спрячется до выбранного дня.</li>
        </ul>
      </section>
      <section className="space-y-2">
        <h3 className="font-semibold">Просрочка</h3>
        <p>
          Карточка ждёт, пока её не разберут. Если срок прошёл, на ней написано,
          сколько дней платёж просрочен. Число в меню слева и красная плашка на
          «Дашборде» и в «Транзакциях» показывают, сколько платежей ждут.
        </p>
      </section>
      <section className="space-y-2">
        <h3 className="font-semibold">Если операцию удалили</h3>
        <p>
          Карточка вернётся в очередь. Если потом восстановить удалённую
          операцию, карточка сама не закроется: разберите её или пропустите.
        </p>
      </section>
    </>
  );
}
