-- Меняем семантику `birth_date_set_at`: теперь ставится ТОЛЬКО когда
-- юзер реально МЕНЯЕТ дату с одной непустой на другую. Первое
-- заполнение (INSERT с birth_date или UPDATE из NULL в значение)
-- больше не пишет set_at — он остаётся NULL.
--
-- Зачем:
--   • UI хочет показывать подпись «Изменено DD.MM.YYYY» под полем ДР
--     только если ДР МЕНЯЛИ. При первом заполнении подпись не нужна
--     (нечего «помечать») — это просто значение, которое юзер вписал.
--   • Yearly-limit (trigger 142) становится дружелюбнее: после первого
--     заполнения у юзера есть ОДНА бесплатная корректировка (исправить
--     опечатку, поправить день после первого ввода). Следующая смена
--     в течение года — уже под limit.
--
-- Backfill для legacy-рядов: set_at остаётся как было (вычистить не
-- можем — нет данных что было INSERT'ом, что UPDATE'ом). Эффект: для
-- legacy-юзеров, чей set_at был выставлен миграцией 132 при первом
-- заполнении post-deploy, подпись всё равно покажется. Это незначимый
-- хвост и сам себя исправит — после следующей реальной смены set_at
-- будет уже актуальным.
-- ─────────────────────────────────────────────────────────────────────────────

create or replace function public.tg_profiles_track_birth_date()
returns trigger
language plpgsql
as $$
begin
  -- INSERT с birth_date — это первое заполнение, не пишем set_at.
  -- UPDATE из NULL в значение — тоже первое заполнение (просто
  -- запоздалое), не пишем set_at.
  -- UPDATE значения на другое значение — это РЕАЛЬНОЕ изменение,
  -- пишем set_at = now().
  if tg_op = 'UPDATE'
     and old.birth_date is not null
     and new.birth_date is distinct from old.birth_date then
    new.birth_date_set_at := now();
  end if;
  return new;
end;
$$;
