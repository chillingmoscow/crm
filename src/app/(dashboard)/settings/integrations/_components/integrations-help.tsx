export function TelegramHelp() {
  return <>
    <Part title="Бот">
      <p>Один бот на организацию. Создайте его в @BotFather и вставьте токен. Сменить бота может только владелец; после смены добавьте нового бота в те же чаты.</p>
    </Part>
    <Part title="Не доставлено">
      <p>Сообщения, которые бот не смог отправить. Чаще всего бота удалили из чата или запретили ему писать. Исправьте причину и нажмите «Отправить снова». «Не отправлять» убирает сообщение из списка.</p>
    </Part>
    <Part title="Уведомления">
      <p>Какое событие в какой чат: новая анкета, приём сотрудника, штрафы и премии. Новые анкеты можно отправлять в отдельный чат. Штрафы и премии отправляются начиная с момента включения.</p>
    </Part>
    <Part title="График и задачи">
      <p>Для каждого заведения: список задач на день (в выбранные дни, если задачи есть) и напоминание сдать пожелания к графику. Время по часам заведения. Чаты выбираются из «Чатов сотрудников».</p>
    </Part>
    <Part title="Чаты сотрудников">
      <p>При приёме бот присылает новому сотруднику приглашения в подходящие по должности чаты, при увольнении исключает его. Для этого бот должен быть администратором чата с правом приглашать и блокировать участников. «Проверить права бота» в меню ⋯ покажет, всё ли в порядке.</p>
    </Part>
    <Part title="Где взять ID чата">
      <p>Откройте чат в web.telegram.org: число после # в адресе и есть ID. У групп оно начинается с -100.</p>
    </Part>
  </>;
}

