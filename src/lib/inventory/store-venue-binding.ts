/**
 * Привязка склада к заведению при синхронизации каталога Quick Resto.
 *
 * Правило одно: автоматика ставит привязку только НОВОМУ складу. У склада,
 * который уже есть в базе, синхронизация к этой колонке не прикасается —
 * что бы там ни стояло, включая пустоту.
 *
 * Почему пустота — это отдельное решение, а не отсутствие решения. В
 * справочнике складов (/org/stores) есть выбор «Не привязан», и он
 * сохраняется как NULL. Раньше payload апсерта собирался как
 * `existingStore?.local_venue_id ?? defaultVenueId`, а `??` эти два состояния
 * не различает: «привязки никогда не было» и «человек её снял» выглядели
 * одинаково, и ближайший синк возвращал привязку обратно. Молча, без записи
 * в журнал. Тот же класс ошибки, что чинили для автоисключений (миграция
 * 231): «пусто» и «человек так решил» были неразличимы.
 *
 * База от этого не страхует, хотя комментарий миграции 215 обещает обратное
 * («на UPDATE триггер не вешаем, чтобы явное "Не привязан" сохранялось»).
 * Склады пишутся через `INSERT ... ON CONFLICT DO UPDATE`, а эффекты
 * BEFORE INSERT-триггера отражаются в `excluded` — триггер отрабатывает на
 * предлагаемой строке ДО детекции конфликта, и его значение уходит на
 * UPDATE-ветку. Проверено на живой БД.
 *
 * Поэтому решение принимается здесь, в форме payload'а: у существующего
 * склада ключа `local_venue_id` в объекте нет ВООБЩЕ — PostgREST не включит
 * колонку в `DO UPDATE SET`, и до неё не дотянется ни апсерт, ни триггер.
 *
 * Побочно это чинит расхождение с обещанием в справке. Удаление заведения
 * обнуляет stores.local_venue_id (SET NULL, см. org/venues/actions.ts), и
 * handbook пишет прямо: склады «отвяжутся и останутся в системе как без
 * заведения». Старый код это обещание нарушал — ближайший синк возвращал
 * привязку к другому заведению.
 *
 * Без импортов из `@/...`, чтобы node:test мог импортировать файл напрямую
 * (тест-раннер не резолвит alias из tsconfig — см. exclusions.ts).
 */

/**
 * Кусок payload'а апсерта склада, отвечающий за привязку к заведению.
 *
 * Пустой объект — это НЕ «привязка пустая», а «колонку не трогаем».
 * Разница принципиальная: пустой объект при спреде не добавит ключ, и
 * колонка не попадёт в `DO UPDATE SET`.
 */
export type StoreVenueBindingPatch = { local_venue_id?: string | null };

export function storeVenueBindingPatch(input: {
  /** Склад уже есть в базе (нашёлся по account_id + external_id). */
  storeExists: boolean;
  /** Куда привязывать новый склад. null — пусть решает триггер миграции 215. */
  defaultVenueId: string | null;
}): StoreVenueBindingPatch {
  if (input.storeExists) return {};
  return { local_venue_id: input.defaultVenueId };
}
