/**
 * Привязка склада к подразделению при синхронизации каталога Quick Resto.
 *
 * Правило то же, что у привязки к заведению (store-venue-binding.ts):
 * автоматика ставит значение только НОВОМУ складу. У склада, который уже есть
 * в базе, синхронизация этих колонок не касается — что бы там ни стояло.
 *
 * Здесь это важнее, чем с заведением: у привязки три состояния — «Не задано»,
 * «Общий склад» и «Подразделение», и два из них (общий склад и конкретное
 * подразделение) человек выбирает осознанно, потому что от выбора зависит,
 * кто платит за недостачу по складу. «Пусто» и «человек так решил» должны
 * оставаться различимы: ближайший синк не вправе молча вернуть склад в
 * «Не задано» или, наоборот, подставить плательщика самому.
 *
 * Решение принимается в форме payload'а, а не в базе: у существующего склада
 * ключей в объекте нет ВООБЩЕ, поэтому PostgREST не включит колонки в
 * `DO UPDATE SET`. Пустой объект — это НЕ «привязка пустая», а «колонки не
 * трогаем».
 *
 * Без импортов из `@/...`, чтобы node:test мог импортировать файл напрямую
 * (тест-раннер не резолвит alias из tsconfig).
 */

export type StoreDepartmentScope = "unset" | "shared" | "department";

/**
 * Кусок payload'а апсерта склада, отвечающий за подразделение. Оба ключа идут
 * вместе: в базе CHECK требует, чтобы scope = 'department' был тогда и только
 * тогда, когда задан department_id.
 */
export type StoreDepartmentBindingPatch = {
  department_scope?: StoreDepartmentScope;
  department_id?: string | null;
};

export function storeDepartmentBindingPatch(input: {
  /** Склад уже есть в базе (нашёлся по account_id + external_id). */
  storeExists: boolean;
}): StoreDepartmentBindingPatch {
  if (input.storeExists) return {};
  return { department_scope: "unset", department_id: null };
}
