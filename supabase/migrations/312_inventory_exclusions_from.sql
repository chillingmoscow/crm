-- Граница ретро-применения исключений по заведению: «Исключения меняют акты
-- начиная с». Ретроактивное применение и снятие правил исключения меняет
-- только акты, бизнес-месяц которых не раньше месяца этой даты (и не
-- зафиксирован в зарплате). NULL — границы нет: меняются все незафиксированные
-- месяцы. Хранится первое число месяца.

alter table public.venues
  add column if not exists inventory_exclusions_from date;

comment on column public.venues.inventory_exclusions_from is
  'Исключения инвентаризации меняют акты начиная с месяца этой даты (первое число месяца). NULL — без границы: все незафиксированные месяцы.';
