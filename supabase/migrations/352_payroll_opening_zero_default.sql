-- Начальный остаток больше не подтверждают (решение владельца 19.11.2026).
--
-- Остаток нужен был один раз — для переезда из прежней системы: в расчёте он
-- учитывается только в месяце начала учёта (calculate.ts, starts_on). Но новый
-- сотрудник из отметок Quick Resto или из команды new_employee получал
-- opening_confirmed = false, и «К выплате» в ведомости превращалось в прочерк,
-- пока кто-то не подтвердит ноль. Теперь новый сотрудник сразу начинает
-- с подтверждённого нуля; пункт «Начальный остаток» из интерфейса убран.
--
-- Тех, кто уже записан с неподтверждённым остатком, эта миграция не трогает:
-- их суммы сверяются с владельцем и вносятся на проде отдельно, один раз,
-- ДО этой миграции. Без этого они застряли бы: база по-прежнему требует
-- подтверждённый остаток для выплаты без основания и для проверки ведомости
-- (payroll_command, миграции 244/245), а подтвердить его в интерфейсе
-- больше негде. Поэтому миграция останавливается, пока такие сотрудники есть.

do $$
declare left_count integer;
begin
  select count(*) into left_count
    from public.payroll_employees
   where not opening_confirmed and not casual;
  if left_count > 0 then
    raise exception 'Сначала подтвердите начальные остатки: % сотрудник(ов) без подтверждённого остатка', left_count;
  end if;
end $$;

alter table public.payroll_employees alter column opening_confirmed set default true;
