-- ============================================================
-- roles.icon — текстовое поле с именем lucide-иконки.
--
-- Используется для кастомизации визуального представления роли
-- в списке должностей и в детальной странице.
--
-- Допустимые значения — белый список лежит в коде на стороне
-- клиента (`role-icons.ts`). На уровне БД ограничений нет:
-- если значение не из белого списка, фронт fallback'нет на
-- иконку по `role.code` (или Shield по умолчанию).
--
-- Системные роли (account_id is null) тоже могут получить icon,
-- но их код всё равно перебивает в getRoleIcon (системные имеют
-- зашитую иконку для консистентности с дизайн-системой).
-- ============================================================

alter table public.roles
  add column if not exists icon text;
